    await page.emulateMedia({ media: 'print' });
    await expect(page.locator('.workspace-sidebar')).toBeHidden();
    await expect(page.locator('.receipt')).toBeVisible();
    await page.emulateMedia({ media: 'screen' });
    await page.goto(saleUrl);
    await expect(page.getByRole('heading', { name: 'Partially returned' })).toBeVisible();
    await expect(page.locator('[data-receipt-total]')).toHaveText('BDT 19.35');
    await page.getByRole('link', { name: 'Record a refund' }).click();
    await page.getByRole('button', { name: 'Return all remaining units' }).click();
    await expect(page.locator('#refund-total')).toHaveText('BDT 9.67');
    await page.getByLabel('Refund reason').fill('Remaining item not suitable for restock');
    await page.getByLabel('I authorize this cash refund').check();
    await page.locator('#refund-submit').click();
    await expect(page).toHaveURL(/\/refunds\/\d+$/);
    await expect(page.locator('[data-refund-total]')).toHaveText('BDT 9.67');
    await page.goto(saleUrl);
    await expect(page.getByRole('heading', { name: 'All units returned' })).toBeVisible();
    await expect(page.getByRole('link', { name: 'Record a refund' })).toHaveCount(0);
    await page.emulateMedia({ media: 'print' });
    await expect(page.locator('.return-summary')).toBeHidden();
    await page.emulateMedia({ media: 'screen' });
    await page.setViewportSize({ width: 1280, height: 900 });
    await page.getByRole('link', { name: 'Products & stock' }).click();
    await page.getByRole('row').filter({ hasText: 'Return Sample E2E' }).getByRole('link', { name: 'Stock ledger' }).click();
